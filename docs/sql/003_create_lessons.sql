CREATE TABLE LESSONS (
    ID NUMBER(19),
    STUDENT_ID NUMBER(19) NOT NULL,
    LESSON_AT DATE NOT NULL,
    STATUS VARCHAR2(20 CHAR) DEFAULT 'SCHEDULED' NOT NULL,
    STATUS_MEMO VARCHAR2(1000 CHAR),
    CREATED_AT DATE DEFAULT CURRENT_DATE NOT NULL,
    
    CONSTRAINT PK_LESSONS PRIMARY KEY(ID),
    
    CONSTRAINT FK_LESSONS_STUDENT
        FOREIGN KEY (STUDENT_ID)
        REFERENCES STUDENTS (ID),
        
    CONSTRAINT CK_LESSONS_STATUS
        CHECK (STATUS IN (
            'SCHEDULED',
            'ATTENDED',
            'CANCELLED',
            'ABSENT'
        ))
    );
    
CREATE SEQUENCE LESSONS_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCYCLE;