CREATE TABLE LESSON_REPORTS (
    ID NUMBER(19),
    LESSON_ID NUMBER(19) NOT NULL,
    CONTENT VARCHAR2(2000 CHAR) NOT NULL,
    NEXT_CHECK VARCHAR2(1000 CHAR),
    CREATED_AT DATE DEFAULT CURRENT_DATE NOT NULL,
    UPDATED_AT DATE DEFAULT CURRENT_DATE NOT NULL,
    
    CONSTRAINT PK_LESSON_REPORTS
        PRIMARY KEY (ID),
    
    CONSTRAINT UQ_LESSON_REPORTS_LESSON
        UNIQUE (LESSON_ID),
        
    CONSTRAINT FK_LESSON_REPORTS_LESSON
        FOREIGN KEY (LESSON_ID)
        REFERENCES LESSONS (ID)
);

CREATE SEQUENCE LESSON_REPORTS_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCYCLE;