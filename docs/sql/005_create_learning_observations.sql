CREATE TABLE LEARNING_OBSERVATIONS (
    ID NUMBER(19),
    LESSON_REPORT_ID NUMBER(19) NOT NULL,
    CATEGORY VARCHAR2(30 CHAR) NOT NULL,
    ITEM VARCHAR2(100 CHAR) NOT NULL,
    MEMO VARCHAR2(1000 CHAR) NOT NULL,
    CREATED_AT DATE DEFAULT CURRENT_DATE NOT NULL,
    UPDATED_AT DATE DEFAULT CURRENT_DATE NOT NULL,
    
    CONSTRAINT PK_LEARNING_OBSERVATIONS
        PRIMARY KEY (ID),
        
    CONSTRAINT FK_OBSERVATIONS_REPORT
        FOREIGN KEY (LESSON_REPORT_ID)
        REFERENCES LESSON_REPORTS (ID),
    
    CONSTRAINT CK_OBSERVATIONS_CATEGORY
        CHECK (
            CATEGORY IN (
                'GRAMMAR',
                'EXPRESSION',
                'PRONUNCIATION',
                'SPEAKING',
                'LISTENING',
                'OTHER'
            )
        )
);

CREATE SEQUENCE LEARNING_OBSERVATIONS_SEQ
    START WITH 1
    INCREMENT BY 1
    NOCYCLE;