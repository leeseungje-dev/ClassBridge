SELECT CONSTRAINT_NAME, SEARCH_CONDITION
FROM USER_CONSTRAINTS
WHERE TABLE_NAME = 'LESSONS'
    AND CONSTRAINT_NAME = 'CK_LESSONS_STATUS';
    
-- 기존 상태 제한 제거
ALTER TABLE LESSONS
    DROP CONSTRAINT CK_LESSONS_STATUS;

-- 지각을 포함한 다섯 가지 상태만 허용
ALTER TABLE LESSONS
    ADD CONSTRAINT CK_LESSONS_STATUS
    CHECK (
        STATUS IN (
            'SCHEDULED',
            'ATTENDED',
            'LATE',
            'CANCELLED',
            'ABSENT'
        )
    );